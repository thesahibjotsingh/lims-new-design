// scripts/gen-known-words.ts
//
// Writes lib/search/known-words.ts: the ordinary English words the spelling help must leave alone.
//
//   npx tsx scripts/gen-known-words.ts
//
// WHY. The spelling help (SearchEngine.correct) puts a word right when it is one letter from a word the site
// uses and is not a word the site uses itself. That is how "gastrits" becomes "gastritis". But the site's own
// vocabulary is only what its pages say, and a patient types ordinary words the pages never use: "thigh",
// "smell", "ringing", "fingers", "chewing". Without this list the help would "correct" those to "high",
// "small", "rang", "fine" and "crew". The list is every English word in the overviews (lib/search/descriptions),
// plus the extra words below. scripts/search-eval.ts fails when an overview uses a word that is not on the list,
// so run this again after writing overviews.

import fs from 'node:fs'
import { DESCRIPTIONS } from '@/lib/search/descriptions/data'

/** Ordinary words about the body, how it feels and what people do, that the overviews may not happen to use. */
const EXTRA = `
abdomen ankle ankles arm arms armpit back bone bones breast breath brow buttock calf cheek chest chin elbow elbows
eyebrow eyelid eyelids face finger fingers foot feet forearm forehead gum gums hair hand hands head heel heels hip hips
jaw knee knees leg legs lip lips mouth nail nails navel neck nose palm palms rib ribs shin shoulder shoulders skin skull
sole spine stomach temple thigh thighs throat thumb toe toes tongue tooth teeth waist wrist wrists
ache aches aching bleed bleeding bleeds blister blisters bruise bruised bruises burn burning burns chill chills chewing
choke choking clicking cough coughing cramp cramps crawling cry crying dizzy drowsy dry faint fainting fatigue feel
feeling feels fever feverish flu gasping giddy hiccup hiccups hungry hurt hurts hurting ill itch itching itchy lump
lumps nausea numb pain painful pale pus ringing rash sneeze sneezing sore sores sweat sweating swell swelling swollen
tender thirsty throbbing tight tired tingle tingling twitch twitching ulcer ulcers unwell vomit vomiting weak weakness
wheeze wheezing yellow
smell smells smelly taste tasting swallow swallowing sleep sleeping sleepy snore snoring wake waking walk walking
sitting standing climbing lifting bending running jumping lying turning twisting stretching
morning evening night daytime midnight yesterday today tomorrow week weeks month months year years often sometimes
always never suddenly slowly gradually frequently regularly daily weekly monthly constantly occasionally
mild moderate severe sharp dull deep constant sudden recurring chronic acute persistent frequent repeated
left right both side sided upper lower front inner outer middle behind around
child children baby babies infant toddler boy girl man men woman women adult adults elderly teenager pregnant
mother father wife husband son daughter brother sister grandmother grandfather
food water milk tea coffee sugar salt oil spicy sweet sour bitter cold hot warm
cycle period periods menstrual discharge
located location open opened closed booked booking taking having getting going looking wanting needing working visiting visiting
reports report timings timing parking charges charged admitted admission discharged visiting appointment appointments
`

const words = new Set<string>()
const take = (text: string) => {
  for (const word of text.toLowerCase().match(/[a-z]{3,}/g) ?? []) words.add(word)
}
take(EXTRA)
for (const entry of DESCRIPTIONS) {
  take(entry.phrases.join(' '))
  take(entry.en.about)
  take(entry.en.points.join(' '))
}

const list = [...words].sort()
const out =
  `// lib/search/known-words.ts\n//\n// GENERATED by scripts/gen-known-words.ts: do not edit by hand. Ordinary English words that the spelling help\n// must leave alone (see that script for why). ${list.length} words.\n\n` +
  `export const KNOWN_WORDS: string = '${list.join(' ')}'\n`
fs.writeFileSync('lib/search/known-words.ts', out)
console.log(`wrote lib/search/known-words.ts: ${list.length} words`)
